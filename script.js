let currentLang = localStorage.getItem("morvanLang") || "pt";
let flipped = 0;

const book = document.getElementById("book");
const mobilePages = document.getElementById("mobilePages");
const currentPage = document.getElementById("currentPage");
const totalPages = document.getElementById("totalPages");

function pageTemplate(page, index) {
  const [theme, title, subtitle, text, pills] = page;
  const cls = theme === "dark" || theme === "cover" ? `page ${theme}` : "page";
  return `
    <article class="${cls}">
      <span class="case-meta">${String(index + 1).padStart(2, "0")}</span>
      <div class="rule"></div>
      <h3>${title}</h3>
      <p class="big-text"><strong>${subtitle}</strong></p>
      <p>${text}</p>
      <div class="pill-row">${pills.map(p => `<span class="pill">${p}</span>`).join("")}</div>
      <span class="page-number">${index + 1}</span>
    </article>
  `;
}

function buildBook() {
  const pages = PORTFOLIO[currentLang];
  totalPages.textContent = pages.length;
  currentPage.textContent = Math.min(flipped * 2 + 1, pages.length);

  const leaves = [];
  for (let i = 0; i < pages.length; i += 2) {
    const front = pageTemplate(pages[i], i);
    const back = pages[i + 1] ? pageTemplate(pages[i + 1], i + 1).replace('<article class="', '<article class="back ') : `<article class="back page"></article>`;
    leaves.push(`<div class="leaf" style="z-index:${pages.length - i}" data-index="${i / 2}">${front}${back}</div>`);
  }

  book.innerHTML = leaves.join("");
  [...book.querySelectorAll(".leaf")].forEach((leaf, idx) => {
    leaf.addEventListener("click", () => {
      if (idx === flipped) nextPage();
      else if (idx === flipped - 1) prevPage();
    });
  });

  mobilePages.innerHTML = pages.map((p, i) => {
    const [theme, title, subtitle, text, pills] = p;
    const dark = theme === "dark" || theme === "cover" ? " dark" : "";
    return `<article class="mobile-page-card${dark}">
      <span class="case-meta">${String(i + 1).padStart(2, "0")}</span>
      <h3>${title}</h3>
      <p><strong>${subtitle}</strong></p>
      <p>${text}</p>
      <div class="pill-row">${pills.map(x => `<span class="pill">${x}</span>`).join("")}</div>
    </article>`;
  }).join("");

  applyFlipState();
}

function applyFlipState() {
  const leaves = [...document.querySelectorAll(".leaf")];
  leaves.forEach((leaf, idx) => {
    leaf.classList.toggle("flipped", idx < flipped);
    leaf.style.zIndex = idx < flipped ? idx + 1 : 100 - idx;
  });
  currentPage.textContent = Math.min(flipped * 2 + 1, PORTFOLIO[currentLang].length);
}

function nextPage() {
  const max = Math.ceil(PORTFOLIO[currentLang].length / 2);
  if (flipped < max) {
    flipped++;
    applyFlipState();
  }
}

function prevPage() {
  if (flipped > 0) {
    flipped--;
    applyFlipState();
  }
}

document.getElementById("nextBtn").addEventListener("click", nextPage);
document.getElementById("prevBtn").addEventListener("click", prevPage);

document.addEventListener("keydown", (event) => {
  if (event.key === "ArrowRight") nextPage();
  if (event.key === "ArrowLeft") prevPage();
});

document.querySelectorAll(".lang").forEach(button => {
  button.addEventListener("click", () => {
    currentLang = button.dataset.lang;
    localStorage.setItem("morvanLang", currentLang);
    document.documentElement.lang = currentLang === "pt" ? "pt-BR" : currentLang === "es" ? "es" : "en";
    document.querySelectorAll(".lang").forEach(b => b.classList.toggle("active", b === button));

    const ui = PORTFOLIO.ui[currentLang];
    document.querySelectorAll("[data-i18n]").forEach(el => {
      const key = el.dataset.i18n;
      if (ui[key]) el.textContent = ui[key];
    });
    flipped = 0;
    buildBook();
  });
});

